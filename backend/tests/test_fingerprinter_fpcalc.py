"""Phase 6.5B.1a exit proof on real ``fpcalc`` (``requires_fpcalc``; the
fixtures are generated by ffmpeg, so ``requires_ffmpeg`` too).

Expected classes come from ``tests/audio_fixtures.py``, written by hand from
how each file was made. Recorded on fpcalc 1.6.2 / ffmpeg 9.0.2
(2026-11-10): 30 s of digital silence prints 221 identical items and is
``low_information`` (not ``too_short``); a 30 s stepped melody prints 221
items (about 7.4 per second) and is ``current``; a 10 s clip is
``too_short``; a 2 s clip makes fpcalc exit 2 with "Empty fingerprint"."""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from app.config import Settings
from app.services.duplicate_detection import MatcherParams
from app.services.fingerprinter import (
    FingerprintFailure,
    FpcalcFingerprinter,
    RawFingerprint,
    classify,
    detect_fingerprinter,
    fpcalc_version_supported,
    probe_fpcalc_version,
)
from tests.audio_fixtures import build_fingerprint_fixtures

pytestmark = [pytest.mark.requires_fpcalc, pytest.mark.requires_ffmpeg]


@pytest.fixture(scope="module")
def fixtures(tmp_path_factory):
    # One build per xdist worker and module, in that worker's own temp dir.
    return build_fingerprint_fixtures(tmp_path_factory.mktemp("fingerprint-fixtures"))


@pytest.fixture(scope="module")
def fp():
    exe = shutil.which("fpcalc")
    version = probe_fpcalc_version(exe)
    return FpcalcFingerprinter(exe, version, timeout_s=60)


@pytest.fixture(scope="module")
def results(fixtures, fp):
    return {name: fp.fingerprint(fx.path) for name, fx in fixtures.items()}


PARAMS = MatcherParams.from_settings(Settings(_env_file=None))


def test_the_installed_fpcalc_is_supported():
    version = probe_fpcalc_version(shutil.which("fpcalc"))

    assert version is not None
    assert fpcalc_version_supported(version)


def test_every_fixture_gets_its_expected_class(fixtures, results):
    for name, fx in fixtures.items():
        result = results[name]
        if fx.expected.startswith("failure:"):
            assert result == FingerprintFailure(fx.expected.split(":", 1)[1]), name
        else:
            assert isinstance(result, RawFingerprint), name
            assert classify(result, PARAMS) == fx.expected, name


def test_the_30s_melody_prints_about_7_items_per_second_with_its_measured_duration(results):
    raw = results["melody30.flac"]

    assert raw.duration_s == pytest.approx(30.0, abs=0.05)
    assert 200 <= len(raw.items) <= 250
    assert all(0 <= item <= 0xFFFFFFFF for item in raw.items)


def test_fingerprinting_is_deterministic(fixtures, fp, results):
    assert fp.fingerprint(fixtures["melody30.flac"].path) == results["melody30.flac"]


def test_silence_is_low_information_not_too_short(results):
    raw = results["silence30.flac"]

    assert len(raw.items) >= PARAMS.min_items
    assert len(set(raw.items)) == 1
    assert classify(raw, PARAMS) == "low_information"


def test_a_file_named_like_an_option_is_fingerprinted(fixtures, fp, tmp_path, monkeypatch):
    odd = tmp_path / "-length.flac"
    odd.write_bytes(fixtures["melody30.flac"].path.read_bytes())
    monkeypatch.chdir(tmp_path)

    raw = fp.fingerprint(Path("-length.flac"))

    assert isinstance(raw, RawFingerprint)
    assert len(raw.items) >= PARAMS.min_items


def test_auto_detects_the_installed_fpcalc(monkeypatch):
    for var in ("AUDIO_FINGERPRINT_BACKEND", "FPCALC_PATH", "FPCALC_TIMEOUT_S"):
        monkeypatch.delenv(var, raising=False)

    detected = detect_fingerprinter(Settings(_env_file=None))

    assert isinstance(detected, FpcalcFingerprinter)
    assert Path(detected.executable).resolve() == Path(shutil.which("fpcalc")).resolve()
    assert fpcalc_version_supported(detected.tool_version)


def test_a_stream_written_flac_keeps_its_print_with_an_unknown_duration(results):
    raw = results["melody30_streamed.flac"]

    assert raw.duration_s is None
    assert raw.items == results["melody30.flac"].items
