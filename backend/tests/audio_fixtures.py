"""Generated audio fixtures for the Phase 6.5 identity tests (spec §8).

Every file is generated by ffmpeg at test time from ``lavfi`` sources with
varied spectral content (pink noise plus two tones; not a pure sine), so no
copyrighted media enters the repository. ``build_identity_fixtures(root)``
writes the set under ``root`` (a per-session, per-xdist-worker temp dir) and
returns ``{name: Fixture}``.

Each fixture carries the codec hint the ingest probe would record and the
**expected exact-equality group**, written here by hand from how the file was
made (review 6.5-U02: expectations never come from re-running the function
under test). Files in the same group hold the same audio and must exact-match;
files in different groups must not.
"""

from __future__ import annotations

import struct
import subprocess
from dataclasses import dataclass
from pathlib import Path

RATE = 44100
SECONDS = 2


@dataclass(frozen=True)
class Fixture:
    path: Path
    codec_hint: str
    group: str | None  # None: no digest expected (unsupported / failed)
    kind: str | None   # expected exact kind, or None


def _source(seed: int, f1: int, f2: int) -> str:
    return (
        f"anoisesrc=color=pink:seed={seed}:amplitude=0.25:sample_rate={RATE}:duration={SECONDS}[n];"
        f"sine=frequency={f1}:sample_rate={RATE}:duration={SECONDS}[s];"
        f"sine=frequency={f2}:sample_rate={RATE}:duration={SECONDS}[t];"
        "[n][s][t]amix=inputs=3,aformat=channel_layouts=stereo"
    )


def _ff(*args: str) -> None:
    subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", *args], check=True)


def _append_ape_and_id3v1(path: Path) -> None:
    """Append an APEv2 tag (header + one item + footer) and then an ID3v1 tag
    to an MP3 file on disk, so it stays a seekable file (spec §3 "still
    unverified" case)."""
    key, value = b"Title", b"Retagged"
    item = struct.pack("<II", len(value), 0) + key + b"\0" + value
    size = len(item) + 32

    def header(flags: int) -> bytes:
        return b"APETAGEX" + struct.pack("<IIII", 2000, size, 1, flags) + b"\0" * 8

    ape = header(0xA0000000) + item + header(0x80000000)
    id3v1 = (b"TAG" + b"Retagged".ljust(30, b"\0") + b"Artist".ljust(30, b"\0")
             + b"Album".ljust(30, b"\0") + b"2020" + b"\0" * 30 + b"\xff")
    with path.open("ab") as fh:
        fh.write(ape + id3v1)


def build_identity_fixtures(root: Path) -> dict[str, Fixture]:
    root.mkdir(parents=True, exist_ok=True)
    p = lambda name: root / name  # noqa: E731

    # Masters: float64 WAV, so every derived integer file is a deliberate
    # quantization of the same source.
    _ff("-f", "lavfi", "-i", _source(7, 440, 1250), "-c:a", "pcm_f64le", str(p("master.wav")))
    _ff("-f", "lavfi", "-i", _source(99, 310, 2700), "-c:a", "pcm_f64le", str(p("other.wav")))

    s24 = ["-sample_fmt", "s32", "-bits_per_raw_sample", "24"]
    # 24-bit family (group G24).
    _ff("-i", str(p("master.wav")), "-c:a", "flac", *s24, str(p("flac24.flac")))
    _ff("-i", str(p("flac24.flac")), "-c:a", "alac", str(p("alac24.m4a")))
    _ff("-i", str(p("flac24.flac")), "-c:a", "pcm_s24le", str(p("wav24.wav")))
    _ff("-i", str(p("flac24.flac")), "-metadata", "title=Retagged", "-c", "copy", str(p("flac24_retag.flac")))
    _ff("-i", str(p("flac24.flac")), "-c:a", "flac", "-compression_level", "0", *s24, str(p("flac24_level0.flac")))
    _ff("-i", str(p("flac24.flac")), "-c", "copy", str(p("flac24_remux.mka")))
    # 16-bit family (group G16), and the 16-bit audio zero-padded into 24 bits.
    _ff("-i", str(p("master.wav")), "-c:a", "flac", "-sample_fmt", "s16", str(p("flac16.flac")))
    _ff("-i", str(p("flac16.flac")), "-c:a", "alac", str(p("alac16.m4a")))
    _ff("-i", str(p("flac16.flac")), "-c:a", "pcm_s16le", str(p("wav16.wav")))
    _ff("-i", str(p("flac16.flac")), "-c:a", "flac", *s24, str(p("flac16_padded24.flac")))
    # 500 ms of leading digital silence before the 24-bit audio (its own group).
    _ff("-f", "lavfi", "-i", f"anullsrc=r={RATE}:cl=stereo:d=0.5", "-i", str(p("flac24.flac")),
        "-filter_complex", "[0][1]concat=n=2:v=0:a=1", "-c:a", "flac", *s24, str(p("flac24_silence.flac")))
    # Float WAV (float kind).
    _ff("-i", str(p("master.wav")), "-c:a", "pcm_f32le", str(p("wav_f32.wav")))
    # Lossy: MP3 320/128 and AAC 256, each with a retagged copy.
    _ff("-i", str(p("master.wav")), "-c:a", "libmp3lame", "-b:a", "320k", str(p("mp3_320.mp3")))
    _ff("-i", str(p("mp3_320.mp3")), "-metadata", "title=Retagged", "-c", "copy", str(p("mp3_320_retag.mp3")))
    _ff("-i", str(p("master.wav")), "-c:a", "libmp3lame", "-b:a", "128k", str(p("mp3_128.mp3")))
    _ff("-i", str(p("mp3_128.mp3")), "-metadata", "title=Retagged", "-c", "copy", str(p("mp3_128_retag.mp3")))
    _ff("-i", str(p("master.wav")), "-c:a", "aac", "-b:a", "256k", str(p("aac256.m4a")))
    _ff("-i", str(p("aac256.m4a")), "-metadata", "title=Retagged", "-c", "copy", str(p("aac256_retag.m4a")))
    # Seekable MP3 with APEv2 + ID3v1 tails appended on disk.
    p("mp3_320_ape_id3v1.mp3").write_bytes(p("mp3_320.mp3").read_bytes())
    _append_ape_and_id3v1(p("mp3_320_ape_id3v1.mp3"))
    # Unrelated source.
    _ff("-i", str(p("other.wav")), "-c:a", "flac", *s24, str(p("unrelated24.flac")))
    # Corrupt: random-looking bytes with a .flac name.
    p("corrupt.flac").write_bytes(bytes((i * 37 + 11) % 256 for i in range(8192)))
    # Opus: not ingestible, only an `unsupported` codec case (no file needed
    # beyond a name; the hint decides).
    p("clip.opus").write_bytes(b"OggS")

    pcm, flt, pkt = "pcm_sha256", "pcm_float_sha256", "packets_sha256"
    table = {
        "flac24.flac": ("flac", "G24", pcm),
        "alac24.m4a": ("alac", "G24", pcm),
        "wav24.wav": ("pcm_s24le", "G24", pcm),
        "flac24_retag.flac": ("flac", "G24", pcm),
        "flac24_level0.flac": ("flac", "G24", pcm),
        "flac24_remux.mka": ("flac", "G24", pcm),
        "flac16.flac": ("flac", "G16", pcm),
        "alac16.m4a": ("alac", "G16", pcm),
        "wav16.wav": ("pcm_s16le", "G16", pcm),
        "flac16_padded24.flac": ("flac", "G16", pcm),
        "flac24_silence.flac": ("flac", "G24_SILENCE", pcm),
        "wav_f32.wav": ("pcm_f32le", "GF32", flt),
        "mp3_320.mp3": ("mp3", "GMP3_320", pkt),
        "mp3_320_retag.mp3": ("mp3", "GMP3_320", pkt),
        "mp3_320_ape_id3v1.mp3": ("mp3", "GMP3_320", pkt),
        "mp3_128.mp3": ("mp3", "GMP3_128", pkt),
        "mp3_128_retag.mp3": ("mp3", "GMP3_128", pkt),
        "aac256.m4a": ("aac", "GAAC_256", pkt),
        "aac256_retag.m4a": ("aac", "GAAC_256", pkt),
        "unrelated24.flac": ("flac", "GUNRELATED", pcm),
        "corrupt.flac": ("flac", None, None),
        "clip.opus": ("opus", None, None),
    }
    return {name: Fixture(p(name), hint, group, kind) for name, (hint, group, kind) in table.items()}


# --- Fingerprint fixtures (6.5B.1a, spec §4.2) --------------------------------
#
# Chromaprint features are chroma over time, so a *steady* signal (silence, a
# sine, a drone, or the stationary tones+noise ``_source`` above) prints one
# repeated item and is ``low_information``. The "varied" fixtures use a stepped
# two-voice melody whose pitches change 3 and 5 times per second. Expected
# classes are written by hand from how each file is made (measured on fpcalc
# 1.6.2: silence and steady tone 221 identical items, diversity 0.0045; the
# melody 0.68).

FP_SECONDS = 30


def _melody(seconds: int) -> str:
    return (
        "aevalsrc=0.4*sin(2*PI*t*220*pow(2\\,floor(mod(t*3\\,24))/12))"
        "+0.3*sin(2*PI*t*330*pow(2\\,floor(mod(t*5\\,17))/12))"
        f":s={RATE}:d={seconds}"
    )


@dataclass(frozen=True)
class FingerprintFixture:
    path: Path
    expected: str  # a classify() state, or "failure:<reason>"


def build_fingerprint_fixtures(root: Path) -> dict[str, FingerprintFixture]:
    root.mkdir(parents=True, exist_ok=True)
    p = lambda name: root / name  # noqa: E731

    _ff("-f", "lavfi", "-i", _melody(FP_SECONDS), "-c:a", "flac", str(p("melody30.flac")))
    _ff("-f", "lavfi", "-i", _melody(10), "-c:a", "flac", str(p("melody10.flac")))
    _ff("-f", "lavfi", "-i", f"sine=frequency=440:sample_rate={RATE}:duration={FP_SECONDS}",
        "-c:a", "flac", str(p("tone30.flac")))
    _ff("-f", "lavfi", "-i", f"anullsrc=r={RATE}:cl=stereo:d={FP_SECONDS}", "-c:a", "flac",
        str(p("silence30.flac")))
    _ff("-f", "lavfi", "-i", _melody(2), "-c:a", "flac", str(p("clip2.flac")))
    # The melody written to a pipe: a FLAC with no duration in its header
    # (fpcalc prints "duration": 0.00 next to a full print).
    with p("melody30_streamed.flac").open("wb") as fh:
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-i", str(p("melody30.flac")),
                        "-f", "flac", "pipe:1"], check=True, stdout=fh)
    # First 20000 bytes of the melody: a truncated FLAC fpcalc cannot read.
    p("truncated.flac").write_bytes(p("melody30.flac").read_bytes()[:20000])
    p("notaudio.flac").write_bytes(b"this is a text file, not audio\n" * 64)

    table = {
        "melody30.flac": "current",
        "melody30_streamed.flac": "current",
        "melody10.flac": "too_short",
        "tone30.flac": "low_information",
        "silence30.flac": "low_information",
        "clip2.flac": "failure:empty_fingerprint",
        "truncated.flac": "failure:decode_error",
        "notaudio.flac": "failure:decode_error",
    }
    return {name: FingerprintFixture(p(name), expected) for name, expected in table.items()}
